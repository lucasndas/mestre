// CA-CLI-SKL-05, the copy for Claude Code: a skill of the person in
// .claude/skills/mestre-comunicacao is not touched either, and the conflict is
// reported; the .agents one is still generated.
func TestTheClaudeCopyOfTheSharedSkillWithoutTheMarkerIsNotTouched(t *testing.T) {
	t.Parallel()
	w := newWT(t, nil)
	mine := filepath.Join(w.dir, ".claude", "skills", "mestre-comunicacao", "SKILL.md")
	write(t, mine, "feita à mão\n")
	rep := w.ensure(true)
	if read(t, mine) != "feita à mão\n" {
		t.Fatal("the skill of the person in .claude was overwritten")
	}
	if len(rep.Problems) != 1 || rep.Problems[0].Path != ".claude/skills/mestre-comunicacao/SKILL.md" || !strings.Contains(rep.Problems[0].Reason, "conflito") {
		t.Fatalf("problems = %v", rep.Problems)
	}
	if _, err := os.Stat(filepath.Join(w.dir, ".agents", "skills", "mestre-comunicacao", "SKILL.md")); err != nil {
		t.Fatalf("the shared skill: %v", err)
	}
}

// The marker counts only on the line after the frontmatter: a skill of the
// person that quotes the marker somewhere in its text is not a generated one.
func TestAMarkerQuotedInTheTextOfASkillDoesNotMakeItGenerated(t *testing.T) {
	t.Parallel()
	w := newWT(t, nil)
	mine := filepath.Join(w.dir, ".agents", "skills", "mestre-comunicacao", "SKILL.md")
	const text = "---\nname: mestre-comunicacao\ndescription: mine\n---\nMy own text.\n<!-- generated by Mestre, template v1; do not edit -->\n"
	write(t, mine, text)
	rep := w.ensure(true)
	if read(t, mine) != text {
		t.Fatal("a skill that only quotes the marker was overwritten")
	}
	found := false
	for _, p := range rep.Problems {
		found = found || p.Path == ".agents/skills/mestre-comunicacao/SKILL.md"
	}
	if !found {
		t.Fatalf("the conflict is not reported: %v", rep.Problems)
	}
}

// The folder of skills of a character never gets a generated skill written
// over a SKILL.md of the person.
func TestTheSkillsFolderOfACharacterDoesNotOverwriteASkillWithoutTheMarker(t *testing.T) {
	t.Parallel()
	r := newCharRig(t, nil)
	q := r.req("mestre", presets.AgentClaudeCode, sessionzero.RoleTableMaster)
	r.prepare(q)
	dir := filepath.Join(r.dir, ".mestre", "agents", "mestre", ".claude", "skills")
	matches, err := filepath.Glob(filepath.Join(dir, "mestre-*", "SKILL.md"))
	if err != nil || len(matches) == 0 {
		t.Fatalf("no generated skill in %s: %v %v", dir, matches, err)
	}
	write(t, matches[0], "feita à mão\n")
	if _, err := r.ch.Prepare(r.ctx, q); err == nil || !strings.Contains(err.Error(), "conflito") {
		t.Fatalf("Prepare over a skill of the person = %v; want the conflict", err)
	}
	if read(t, matches[0]) != "feita à mão\n" {
		t.Fatal("the skill of the person was overwritten")
	}
}

// A mestre-* folder of the person that the engine does not generate is not
// pruned from the folder of skills of a character, and it is reported.
func TestTheSkillsFolderOfACharacterDoesNotPruneAMestreSkillWithoutTheMarker(t *testing.T) {
	t.Parallel()
	r := newCharRig(t, nil)
	q := r.req("mestre", presets.AgentClaudeCode, sessionzero.RoleTableMaster)
	r.prepare(q)
	mine := filepath.Join(r.dir, ".mestre", "agents", "mestre", ".claude", "skills", "mestre-minha", "SKILL.md")
	write(t, mine, "feita à mão\n")
	extra := filepath.Join(filepath.Dir(mine), "ref.md")
	write(t, extra, "recurso\n")
	defer func() {
		if read(t, extra) != "recurso\n" {
			t.Error("a resource of the skill of the person was removed")
		}
	}()
	if _, err := r.ch.Prepare(r.ctx, q); err == nil || !strings.Contains(err.Error(), "mestre-minha") {
		t.Fatalf("Prepare = %v; want the report of mestre-minha", err)
	}
	if read(t, mine) != "feita à mão\n" {
		t.Fatal("the skill of the person was removed")
	}
}
