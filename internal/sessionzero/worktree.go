// ExcludeBlock is the name of the block of the Mestre in info/exclude
// (docs/sessao-zero/mesa.md#gitinfoexclude).
const ExcludeBlock = "managed"

// Paths of the files the Mestre generates in a worktree, relative to it
// (docs/sessao-zero/mesa.md#arquivos-gerados-no-worktree).
const (
	agentsSkill  = ".agents/skills/mestre-comunicacao/SKILL.md"
	claudeSkill  = ".claude/skills/mestre-comunicacao/SKILL.md"
	claudeConfig = ".claude/settings.local.json"
	agyHooks     = ".agents/hooks.json"
)

// maxManaged bounds what is read of a file the engine merges into.
const maxManaged = 4 << 20

// skillMarker starts the line that marks a generated skill
// (docs/cli/skills-geradas.md#formato-comum).
const skillMarker = "<!-- generated by Mestre, template v"

// CommunicationSkill is the SKILL.md of mestre-comunicacao, the only skill
// shared by all the agents of a worktree. The orientation text comes from
// the model the Citadel versions (docs/cli/skills-geradas.md); this is the
// part every worktree has from the start.
func CommunicationSkill() []byte {
	return []byte(`---
name: mestre-comunicacao
description: >-
  Talk to other agents, read and write notes (pergaminhos), finish a task and
  wait without blocking, using the ` + "`mestre`" + ` CLI. Use whenever you need another
  agent, a shared note, or must report that your task is done.
---
` + skillMarker + ModelVersion + `; do not edit -->
# Talking to the other agents

- The CLI is ` + "`mestre`" + ` (on the PATH, or in ` + "`$MESTRE_CLI`" + `). ` + "`mestre help`" + ` lists what you can do.
- Ask another agent with ` + "`mestre ask`" + `; use ` + "`--no-wait`" + ` for long work.
- A command that answers ` + "`queued`" + ` (text ` + "`PENDING:`" + `) was only accepted: say it is
  pending, never that it happened.
- Finish every task with ` + "`mestre done \"<summary>\"`" + `.
`)
}

// Worktree makes the files the providers need in a worktree of the project:
// the shared skill, the hook files and the exclusions that keep all of it out
// of git. The main clone is one such worktree (the session zero of the
// workspace); the tables reuse it (docs/sessao-zero/mesa.md).
type Worktree struct {
	// Providers gives the hook files of each provider.
	Providers *providers.Registry
	// OS is the system of the machine ("" is this one).
	OS string
	// Binary is the stable absolute path of the `mestre` binary.
	Binary string
	// Skill is the SKILL.md of mestre-comunicacao; nil is CommunicationSkill.
	Skill []byte
}

// WorktreeRequest says where to generate.
type WorktreeRequest struct {
	// Dir is the worktree, an absolute path.
	Dir string
	// Repo is the worktree opened by its record (OpenPrincipal).
	Repo gitx.Repo
	// ExcludeMestre puts /.mestre/ whole in the exclusions: the workspace
	// keeps .mestre/ local (the default until the users answer).
	ExcludeMestre bool
}

// WorktreeReport is what Ensure did.
type WorktreeReport struct {
	// Written are the files made or changed, relative to the worktree.
	Written []string
	// Problems are the files it did not touch, with the reason; the
	// characters of the provider that depends on one do not start there
	// (docs/sessao-zero/mesa.md#regras-e-erros).
	Problems []Problem
}

// Ensure generates the files and the exclusions. It is idempotent: with
// nothing changed in the models, not a byte or a date changes. It touches
// only the part of the Mestre of each file and never the .gitignore.
func (w Worktree) Ensure(ctx context.Context, req WorktreeRequest) (WorktreeReport, error) {
	var rep WorktreeReport
	if req.Dir == "" || !filepath.IsAbs(req.Dir) || req.Repo == nil {
		return rep, errors.New("sessionzero: a worktree needs an absolute folder and its repository")
	}
	prev, err := req.Repo.ExcludeBlock(ctx, ExcludeBlock)
	if err != nil {
		return rep, fmt.Errorf("read the exclusions: %w", err)
	}
	created := map[string]bool{} // files the Mestre created, hence excluded
	for _, id := range []providers.ID{providers.ClaudeCode, providers.Antigravity} {
		ad, err := w.Providers.For(id)
		if err != nil {
			return rep, err
		}
		files, err := ad.HookFiles(providers.HookFilesRequest{OS: w.OS, Root: req.Dir, Binary: w.Binary})
		if err != nil {
			rep.Problems = append(rep.Problems, Problem{Path: string(id), Reason: "não foi possível montar os hooks: " + err.Error()})
			continue
		}
		for _, f := range files {
			rel, err := filepath.Rel(req.Dir, f.Path)
			if err != nil {
				return rep, err
			}
			rel = filepath.ToSlash(rel)
			existed, changed, err := mergeFile(f)
			switch {
			case err != nil:
				rep.Problems = append(rep.Problems, Problem{Path: rel, Reason: err.Error()})
			default:
				created[rel] = !existed
				if changed {
					rep.Written = append(rep.Written, rel)
				}
			}
		}
	}
	skill := w.Skill
	if skill == nil {
		skill = CommunicationSkill()
	}
	for _, rel := range []string{agentsSkill, claudeSkill} {
		changed, err := writeSkill(filepath.Join(req.Dir, filepath.FromSlash(rel)), skill)
		switch {
		case err != nil:
			rep.Problems = append(rep.Problems, Problem{Path: rel, Reason: err.Error()})
		case changed:
			rep.Written = append(rep.Written, rel)
		}
	}
	patterns := w.excludePatterns(prev, created, req.ExcludeMestre)
	if !slices.Equal(prev, patterns) {
		if err := req.Repo.SetExcludeBlock(ctx, ExcludeBlock, patterns); err != nil {
			return rep, fmt.Errorf("write the exclusions: %w", err)
		}
	}
	// A file the project versions keeps showing in git status unless git is
	// told to ignore the local change (docs/sessao-zero/mesa.md#mescla-gerenciada).
	for _, rel := range []string{claudeConfig, agyHooks} {
		if slices.ContainsFunc(rep.Problems, func(p Problem) bool { return p.Path == rel }) {
			continue
		}
		if tracked, err := isTracked(ctx, req.Repo, rel); err != nil {
			return rep, err
		} else if tracked {
			if err := req.Repo.SetSkipWorktree(ctx, true, rel); err != nil {
				return rep, fmt.Errorf("skip-worktree %s: %w", rel, err)
			}
		}
	}
	return rep, nil
}

// SetExcludeMestre changes only the line of /.mestre/ in the exclusions (the
// answer about versioning), keeping the rest of the block.
func (w Worktree) SetExcludeMestre(ctx context.Context, repo gitx.Repo, exclude bool) error {
	prev, err := repo.ExcludeBlock(ctx, ExcludeBlock)
	if err != nil {
		return fmt.Errorf("read the exclusions: %w", err)
	}
	patterns := w.excludePatterns(prev, nil, exclude)
	if slices.Equal(prev, patterns) {
		return nil
	}
	if err := repo.SetExcludeBlock(ctx, ExcludeBlock, patterns); err != nil {
		return fmt.Errorf("write the exclusions: %w", err)
	}
	return nil
}

// excludePatterns is the content of the block, in the order of the document.
// .agents/hooks.json is excluded only when the Mestre made the file: it was
// absent, or an earlier block already excluded it. A file of the project not
// versioned yet stays visible to the person.
func (w Worktree) excludePatterns(prev []string, created map[string]bool, excludeMestre bool) []string {
	p := []string{
		"/.mestre/agents/", "/.mestre/anexos/", "/.mestre/run/",
		"/.agents/skills/mestre-*/", "/.claude/skills/mestre-*/", "/.agents/agents/mestre-*.md",
		"/" + claudeConfig,
	}
	if created[agyHooks] || slices.Contains(prev, "/"+agyHooks) {
		p = append(p, "/"+agyHooks)
	}
	if excludeMestre {
		p = append(p, "/.mestre/")
	}
	return p
}

// isTracked says whether the project versions the file at HEAD.
func isTracked(ctx context.Context, repo gitx.Repo, rel string) (bool, error) {
	_, err := repo.ReadFile(ctx, "HEAD", rel)
	switch {
	case err == nil:
		return true, nil
	case errors.Is(err, gitx.ErrFileNotFound), errors.Is(err, gitx.ErrRefNotFound):
		return false, nil
	}
	return false, fmt.Errorf("read %s at HEAD: %w", rel, err)
}

// mergeFile applies the managed part of a file: it reads the file, builds the
// new content and writes it only if it differs. A file that cannot be merged
// (a JSON that is not valid) is not touched. existed says whether the file
// was there before.
func mergeFile(f providers.ManagedFile) (existed, changed bool, err error) {
	cur, before, err := safefile.Read(f.Path, maxManaged)
	switch {
	case err == nil:
		existed = true
	case errors.Is(err, fs.ErrNotExist):
		cur, before = nil, safefile.Info{}
	default:
		return false, false, fmt.Errorf("não foi lido: %w", err)
	}
	next, err := f.Merge(cur)
	if err != nil {
		return existed, false, fmt.Errorf("não foi alterado: %w", err)
	}
	if existed && bytes.Equal(cur, next) {
		return true, false, nil
	}
	guard := func(now safefile.Info) error {
		if !now.Same(before) {
			return errors.New("o arquivo mudou enquanto era mesclado")
		}
		return nil
	}
	if err := safefile.Write(f.Path, next, safefile.Options{Guard: guard}); err != nil {
		return existed, false, fmt.Errorf("não foi gravado: %w", err)
	}
	return existed, true, nil
}

// writeSkill writes a generated skill, leaving alone a file of the same name
// that is not generated (docs/cli/skills-geradas.md: a conflict is reported).
func writeSkill(file string, content []byte) (bool, error) {
	cur, before, err := safefile.Read(file, maxManaged)
	switch {
	case err == nil:
		if !bytes.Contains(cur, []byte(skillMarker)) {
			return false, errors.New("já existe e não tem o marcador de arquivo gerado: conflito, nada foi alterado")
		}
		if bytes.Equal(cur, content) {
			return false, nil
		}
	case errors.Is(err, fs.ErrNotExist):
		before = safefile.Info{}
	default:
		return false, fmt.Errorf("não foi lido: %w", err)
	}
	guard := func(now safefile.Info) error {
		if !now.Same(before) {
			return errors.New("o arquivo mudou enquanto era gerado")
		}
		return nil
	}
	if err := safefile.Write(file, content, safefile.Options{Guard: guard}); err != nil {
		return false, fmt.Errorf("não foi gravado: %w", err)
	}
	return true, nil
}

// MestreFiles lists the files of .mestre/ that go into the project when it is
// versioned: everything except the execution folders. Paths are relative to
// the main clone, with slashes.
func MestreFiles(root string) ([]string, error) {
	var out []string
	base := filepath.Join(root, MestreDir)
	var walk func(dir, rel string) error
	walk = func(dir, rel string) error {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return err
		}
		for _, e := range entries {
			name := e.Name()
			childRel := path.Join(rel, name)
			if rel == MestreDir && slices.Contains(ExecutionDirs, name) {
				continue
			}
			switch {
			case e.Type()&fs.ModeSymlink != 0:
				continue // a link is never followed nor versioned
			case e.IsDir():
				if err := walk(filepath.Join(dir, name), childRel); err != nil {
					return err
				}
			case e.Type().IsRegular() && !strings.HasPrefix(name, "."):
				out = append(out, childRel)
			}
		}
		return nil
	}
	if err := walk(base, MestreDir); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	slices.Sort(out)
	return out, nil
}
