package i18n

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

// GeneratedTS is the path, from the root of the repository, of the generated
// messages of the panel.
const GeneratedTS = "web/src/gen/messages.ts"

//go:generate go run ./gen ../../web/src/gen/messages.ts

// GenerateTS returns the source of web/src/gen/messages.ts: every text of the
// catalogs of the engine, in both languages, so that the panel says a refusal,
// a notice or a card in the language of the user from its code and params and
// never repeats the text in catalogs of its own. The area api (the message of an
// error of the API, for a client that has not the code) and the area person (the
// texts of the CLI of a person, which the panel never shows) stay out: the panel
// translates those errors by their code, in its own catalog of errors. Same input, same bytes, so a
// test can regenerate in memory and compare with the committed file.
func GenerateTS() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate from internal/i18n/locales; DO NOT EDIT.\n\n")
	b.WriteString("export const messages = {\n")
	for _, lang := range []string{PtBR, En} {
		cat := Catalog(lang)
		keys := make([]string, 0, len(cat))
		for k := range cat {
			if strings.HasPrefix(k, "api.") || strings.HasPrefix(k, "person.") {
				continue // the API (the panel has its own by the code) and the CLI of a person (the panel never shows it)
			}
			keys = append(keys, k)
		}
		sort.Strings(keys)
		name, _ := json.Marshal(lang)
		fmt.Fprintf(&b, "\t%s: {\n", name)
		for _, k := range keys {
			kk, _ := json.Marshal(k)
			vv, err := marshalNoEscape(cat[k])
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&b, "\t\t%s: %s,\n", kk, vv)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("} as const satisfies Record<string, Record<string, string>>\n\n")
	b.WriteString("export type MessageCode = keyof (typeof messages)[\"pt-BR\"]\n")
	return b.Bytes(), nil
}

// marshalNoEscape is the JSON string of a text without the HTML escapes of encoding/json
// (a "<" in a text stays a "<", as in the catalog).
func marshalNoEscape(s string) (string, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		return "", err
	}
	return string(bytes.TrimRight(b.Bytes(), "\n")), nil
}
