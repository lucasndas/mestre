// Generate returns the source of terms_gen.go for the terms of the glossary:
// the help texts the panel and Telegram embed. Same input, same bytes, so a
// test can regenerate in memory and compare with the committed file.
func Generate(terms []Term) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate from docs/produto/glossario.md; DO NOT EDIT.\n\n")
	b.WriteString("package glossary\n\n")
	b.WriteString("// Terms are the rows of the glossary table, in document order.\n")
	b.WriteString("var Terms = []Term{\n")
	for _, t := range terms {
		fmt.Fprintf(&b, "\t{Name: %q, Help: %q, Real: %q, Detail: %q, En: English{Key: %q, Name: %q, Help: %q, Real: %q}},\n",
			t.Name, t.Help, t.Real, t.Detail, t.Name, t.En.Name, t.En.Help, t.En.Real)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated glossary: %w", err)
	}
	return out, nil
}

// GenerateTS returns the source of web/src/gen/glossary.ts: the terms the panel
// shows in its help, in both languages. The panel never writes a help text of
// its own, and a term it uses that is not here is a type error.
func GenerateTS(terms []Term) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate from docs/produto/glossario.md and glossario-en.md; DO NOT EDIT.\n\n")
	b.WriteString("export interface GlossaryText {\n\tname: string\n\thelp: string\n\treal: string\n}\n\n")
	b.WriteString("export const glossary = {\n")
	for _, t := range terms {
		pt, err := json.Marshal(GlossaryJSON{Name: t.Name, Help: t.Help, Real: t.Real})
		if err != nil {
			return nil, err
		}
		en, err := json.Marshal(GlossaryJSON{Name: t.En.Name, Help: t.En.Help, Real: t.En.Real})
		if err != nil {
			return nil, err
		}
		key, _ := json.Marshal(t.Name)
		fmt.Fprintf(&b, "\t%s: { \"pt-BR\": %s, en: %s },\n", key, pt, en)
	}
	b.WriteString("} as const satisfies Record<string, { \"pt-BR\": GlossaryText; en: GlossaryText }>\n\n")
	b.WriteString("export type TermKey = keyof typeof glossary\n")
	return b.Bytes(), nil
}

// GlossaryJSON is a text of a term in the TypeScript file.
type GlossaryJSON struct {
	Name string `json:"name"`
	Help string `json:"help"`
	Real string `json:"real"`
}
